#Requires -Version 5.1
<#
.SYNOPSIS
    Creates a local release package for KatyPS5 matching the GitHub Actions workflow format.
    
.DESCRIPTION
    This script compiles KatyPS5 and packages it in the standard release structure:
    - _Build/releases/vX.Y.Z/windows/ (binaries + Qt6 DLLs)
    - _Build/releases/vX.Y.Z/manifest.json (release metadata)
    - _Build/releases/vX.Y.Z/notes.md (release notes)
    
    The structure matches what's generated by GitHub Actions in erickson558/KatyPS5 releases.

.PARAMETER Version
    Semantic version (e.g., "0.4.2"). If not specified, reads from CMakeLists.txt.

.PARAMETER BuildType
    Build configuration: "Release" (default) or "Debug".

.PARAMETER SkipCompile
    Skip compilation; only package existing build artifacts.

.PARAMETER Verbose
    Show detailed build and packaging information.

.EXAMPLE
    .\create-local-release.ps1
    # Compiles v0.4.2 (from CMakeLists.txt) and creates release package
    
    .\create-local-release.ps1 -Version "0.4.3" -BuildType Release
    # Compiles v0.4.3 in Release mode and packages it
    
    .\create-local-release.ps1 -SkipCompile -Version "0.4.2"
    # Packages existing v0.4.2 build without recompiling
#>

param(
    [string]$Version,
    [ValidateSet("Release", "Debug")]
    [string]$BuildType = "Release",
    [switch]$SkipCompile,
    [switch]$Verbose
)

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

# ============================================================================
# CONFIGURATION
# ============================================================================

$ProjectRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$BuildDir = Join-Path $ProjectRoot "_Build"
$WindowsBuildDir = Join-Path $BuildDir "windows"
$ReleasesDir = Join-Path $BuildDir "releases"

# Detect version from CMakeLists.txt if not specified
if (-not $Version) {
    $cmakePath = Join-Path $ProjectRoot "CMakeLists.txt"
    if (-not (Test-Path $cmakePath)) {
        Write-Error "CMakeLists.txt not found at $cmakePath"
        exit 1
    }
    
    $match = Select-String -Path $cmakePath -Pattern 'project\(.*VERSION\s+([\d.]+)' | Select-Object -First 1
    if ($match) {
        $Version = $match.Matches[0].Groups[1].Value
    } else {
        Write-Error "Could not detect version from CMakeLists.txt. Please specify -Version."
        exit 1
    }
}

$VersionTag = "v$Version"
$ReleaseDir = Join-Path $ReleasesDir $VersionTag
$WindowsReleaseDir = Join-Path $ReleaseDir "windows"
$Qt6BinDir = "$Env:Qt6_DIR/bin"  # Standard Qt6 installation location

Write-Host "═══════════════════════════════════════════════════════════════════" -ForegroundColor Cyan
Write-Host "  KatyPS5 Local Release Creator - $VersionTag" -ForegroundColor Cyan
Write-Host "═══════════════════════════════════════════════════════════════════" -ForegroundColor Cyan
Write-Host ""

# ============================================================================
# STEP 1: VERIFY PREREQUISITES
# ============================================================================

Write-Host "📋 Checking prerequisites..." -ForegroundColor Yellow

$tools = @{
    "cmake"   = "cmake --version"
    "ninja"   = "ninja --version"
    "git"     = "git --version"
}

foreach ($tool in $tools.Keys) {
    try {
        $cmd = $tools[$tool]
        Invoke-Expression $cmd | Out-Null
        Write-Host "  ✓ $tool found" -ForegroundColor Green
    } catch {
        Write-Host "  ✗ $tool NOT FOUND" -ForegroundColor Red
        Write-Host ""
        Write-Host "Please run: .\install-build-tools.ps1" -ForegroundColor Yellow
        exit 1
    }
}

# Verify Qt6
if (-not $Env:Qt6_DIR) {
    Write-Host "  ⚠ Qt6_DIR not set. Attempting to find Qt6..." -ForegroundColor Yellow
    
    $qt6Paths = @(
        "C:\Qt\6.10.3\msvc2022_64",
        "C:\Qt\6.9.0\msvc2022_64",
        "C:\Qt\6.8.0\msvc2022_64"
    )
    
    $found = $false
    foreach ($path in $qt6Paths) {
        if (Test-Path $path) {
            $Env:Qt6_DIR = $path
            Write-Host "  ✓ Qt6 found at: $path" -ForegroundColor Green
            $found = $true
            break
        }
    }
    
    if (-not $found) {
        Write-Host "  ✗ Qt6 NOT FOUND" -ForegroundColor Red
        Write-Host ""
        Write-Host "Please:" -ForegroundColor Yellow
        Write-Host "  1. Run: .\install-build-tools.ps1" -ForegroundColor Yellow
        Write-Host "  2. Download and install Qt6 from: https://www.qt.io/download" -ForegroundColor Yellow
        Write-Host "  3. Set environment variable Qt6_DIR to your Qt6 installation" -ForegroundColor Yellow
        exit 1
    }
}

Write-Host "  ✓ Qt6 found at: $Env:Qt6_DIR" -ForegroundColor Green
Write-Host ""

# ============================================================================
# STEP 2: COMPILE IF NEEDED
# ============================================================================

if (-not $SkipCompile) {
    Write-Host "🔨 Compiling KatyPS5 ($BuildType mode)..." -ForegroundColor Yellow
    Write-Host ""
    
    # Run compile.ps1
    $compileScript = Join-Path $ProjectRoot "compile.ps1"
    if (-not (Test-Path $compileScript)) {
        Write-Error "compile.ps1 not found at $compileScript"
        exit 1
    }
    
    $compileArgs = @(
        "-BuildType", $BuildType
        "-Version", $Version
    )
    if ($Verbose) {
        $compileArgs += "-Verbose"
    }
    
    & $compileScript @compileArgs
    if ($LASTEXITCODE -ne 0) {
        Write-Error "Compilation failed with exit code $LASTEXITCODE"
        exit 1
    }
    
    Write-Host ""
}

# ============================================================================
# STEP 3: VERIFY BUILD ARTIFACTS
# ============================================================================

Write-Host "✓ Verifying build artifacts..." -ForegroundColor Yellow

$emulatorExe = Join-Path $WindowsBuildDir "src\katyEmulator\katy_emulator.exe"
$launcherExe = Join-Path $WindowsBuildDir "src\launcher\launcher.exe"
$installDir = Join-Path $WindowsBuildDir "install"

if (-not (Test-Path $emulatorExe)) {
    Write-Error "katy_emulator.exe not found at $emulatorExe. Compilation may have failed."
    exit 1
}

if (-not (Test-Path $launcherExe)) {
    Write-Error "launcher.exe not found at $launcherExe. Compilation may have failed."
    exit 1
}

Write-Host "  ✓ katy_emulator.exe found ($(((Get-Item $emulatorExe).Length / 1MB).ToString('F2')) MB)" -ForegroundColor Green
Write-Host "  ✓ launcher.exe found ($(((Get-Item $launcherExe).Length / 1KB).ToString('F2')) KB)" -ForegroundColor Green
Write-Host ""

# ============================================================================
# STEP 4: CREATE RELEASE DIRECTORY STRUCTURE
# ============================================================================

Write-Host "📦 Creating release package structure..." -ForegroundColor Yellow

# Remove old release if exists
if (Test-Path $ReleaseDir) {
    Write-Host "  Removing existing $VersionTag release directory..." -ForegroundColor Gray
    Remove-Item -Path $ReleaseDir -Recurse -Force
}

# Create release directories
$null = New-Item -ItemType Directory -Path $WindowsReleaseDir -Force
$null = New-Item -ItemType Directory -Path (Join-Path $ReleaseDir "packages") -Force

Write-Host "  ✓ Created: $WindowsReleaseDir" -ForegroundColor Green

# ============================================================================
# STEP 5: COPY BINARIES AND DEPENDENCIES
# ============================================================================

Write-Host "🔄 Copying binaries and Qt6 runtime dependencies..." -ForegroundColor Yellow

# List of required Qt6 runtime DLLs
$qt6Dlls = @(
    "Qt6Core.dll",
    "Qt6Gui.dll",
    "Qt6Widgets.dll",
    "Qt6Network.dll",
    "Qt6Svg.dll",
    "libwinpthread-1.dll",
    "icuuc.dll",
    "icudt.dll",
    "icuin.dll"
)

# Copy main executables
Copy-Item -Path $emulatorExe -Destination $WindowsReleaseDir
Copy-Item -Path $launcherExe -Destination $WindowsReleaseDir

Write-Host "  ✓ Copied executables" -ForegroundColor Green

# Copy Qt6 runtime DLLs
$qt6BinPath = Join-Path $Env:Qt6_DIR "bin"
if (-not (Test-Path $qt6BinPath)) {
    Write-Host "  ⚠ Qt6 bin directory not found at: $qt6BinPath" -ForegroundColor Yellow
    Write-Host "     Attempting alternative search..." -ForegroundColor Gray
    
    # Try finding dlls in the Qt6 installation directory
    $qt6BinPath = $null
    foreach ($searchPath in @(
        (Join-Path $Env:Qt6_DIR "bin"),
        (Join-Path $Env:Qt6_DIR "lib"),
        (Join-Path $Env:Qt6_DIR "libexec")
    )) {
        if (Test-Path $searchPath) {
            $qt6BinPath = $searchPath
            Write-Host "     Found in: $searchPath" -ForegroundColor Green
            break
        }
    }
    
    if (-not $qt6BinPath) {
        Write-Host "     Could not locate Qt6 runtime directory" -ForegroundColor Yellow
    }
}

$missingDlls = @()
foreach ($dll in $qt6Dlls) {
    $dllPath = Join-Path $qt6BinPath $dll
    if (Test-Path $dllPath) {
        Copy-Item -Path $dllPath -Destination $WindowsReleaseDir -Force
    } else {
        Write-Host "  ⚠ Optional DLL not found: $dll (searched: $dllPath)" -ForegroundColor Gray
    }
}

Write-Host "  ✓ Copied Qt6 runtime libraries" -ForegroundColor Green

# Copy Qt6 plugin directories
$pluginDirs = @("platforms", "iconengines", "imageformats", "styles", "generic", "networkinformation", "tls")
$qtPluginsDir = Join-Path $Env:Qt6_DIR "plugins"

if (-not (Test-Path $qtPluginsDir)) {
    Write-Host "  ⚠ Qt6 plugins directory not found at: $qtPluginsDir" -ForegroundColor Yellow
    Write-Host "     Plugins may not be included in this release" -ForegroundColor Gray
} else {
    foreach ($plugin in $pluginDirs) {
        $srcPlugin = Join-Path $qtPluginsDir $plugin
        $destPlugin = Join-Path $WindowsReleaseDir $plugin
        
        if (Test-Path $srcPlugin) {
            $null = New-Item -ItemType Directory -Path $destPlugin -Force
            Copy-Item -Path "$srcPlugin\*" -Destination $destPlugin -Recurse -Force
        } else {
            Write-Host "  ℹ Optional plugin not found: $plugin" -ForegroundColor Gray
        }
    }
    
    Write-Host "  ✓ Copied Qt6 plugins" -ForegroundColor Green
}

# Copy LICENSE
$licensePath = Join-Path $ProjectRoot "LICENSE"
if (Test-Path $licensePath) {
    Copy-Item -Path $licensePath -Destination $WindowsReleaseDir
    Write-Host "  ✓ Copied LICENSE" -ForegroundColor Green
}

# Copy Qt LICENSES
$qtLicensesDir = Join-Path $Env:Qt6_DIR "licenses"
if (-not (Test-Path $qtLicensesDir)) {
    Write-Host "  ℹ Qt6 licenses directory not found at: $qtLicensesDir" -ForegroundColor Gray
} else {
    $qtLicensesDest = Join-Path $WindowsReleaseDir "LICENSES"
    $null = New-Item -ItemType Directory -Path $qtLicensesDest -Force
    Copy-Item -Path "$qtLicensesDir\*" -Destination $qtLicensesDest -Recurse -Force
    Write-Host "  ✓ Copied Qt6 licenses" -ForegroundColor Green
}

# Copy Kyty historical license
$kytyLicense = Join-Path $ProjectRoot "LICENSES\Kyty-MIT.txt"
if (Test-Path $kytyLicense) {
    $licensesDir = Join-Path $WindowsReleaseDir "LICENSES"
    $null = New-Item -ItemType Directory -Path $licensesDir -Force
    Copy-Item -Path $kytyLicense -Destination $licensesDir -Force
}

Write-Host ""

# ============================================================================
# STEP 6: CREATE MANIFEST.JSON
# ============================================================================

Write-Host "📝 Creating manifest.json..." -ForegroundColor Yellow

# Get git commit hash
try {
    $commitHash = (git -C $ProjectRoot rev-parse HEAD 2>&1)
    if (-not $commitHash -or $LASTEXITCODE -ne 0) {
        $commitHash = "unknown"
    }
} catch {
    $commitHash = "unknown"
}

if ($commitHash.Length -ge 7) {
    $commitShort = $commitHash.Substring(0, 7)
} else {
    $commitShort = $commitHash
}

# Get current git branch
try {
    $gitBranch = (git -C $ProjectRoot rev-parse --abbrev-ref HEAD 2>&1)
    if (-not $gitBranch -or $LASTEXITCODE -ne 0) {
        $gitBranch = "unknown"
    }
} catch {
    $gitBranch = "unknown"
}

# Build metadata
$releaseDate = Get-Date -Format "yyyy-MM-dd"
$releaseDateTime = Get-Date -Format "o"
$releaseTag = "KatyPS5-$releaseDate-$commitShort"

$manifest = @{
    version = $Version
    tag = $VersionTag
    source_commit = $commitHash
    source_commit_short = $commitShort
    git_branch = $gitBranch
    release_tag = $releaseTag
    release_date = $releaseDate
    release_date_iso = $releaseDateTime
    github_repository = "erickson558/KatyPS5"
    build_type = $BuildType
    build_platform = "Windows (Local)"
    build_tool_versions = @{
        cmake = (cmake --version 2>$null | Select-Object -First 1) -replace "^.*version ", ""
        ninja = (ninja --version 2>$null)
        qt6 = $Env:Qt6_DIR
    }
    assets = @(
        @{
            file = "KatyPS5-$VersionTag-Windows-x64.zip"
            platform = "Windows"
            architecture = "x64"
        }
    )
}

$manifestJson = $manifest | ConvertTo-Json -Depth 10
$manifestPath = Join-Path $ReleaseDir "manifest.json"
$manifestJson | Out-File -FilePath $manifestPath -Encoding UTF8 -Force

Write-Host "  ✓ Created manifest.json" -ForegroundColor Green
if ($Verbose) {
    Write-Host "    Release tag: $releaseTag" -ForegroundColor Gray
    Write-Host "    Commit: $commitHash" -ForegroundColor Gray
    Write-Host "    Branch: $gitBranch" -ForegroundColor Gray
}

# ============================================================================
# STEP 7: CREATE RELEASE NOTES
# ============================================================================

Write-Host "📝 Creating release notes..." -ForegroundColor Yellow

$notesPath = Join-Path $ReleaseDir "notes.md"
$changelogPath = Join-Path $ProjectRoot "CHANGELOG.md"

$notesContent = @"
# KatyPS5 $VersionTag

**Build Information:**
- **Commit:** [$commitShort](https://github.com/erickson558/KatyPS5/commit/$commitHash)
- **Build Date:** $releaseDate
- **Build Type:** $BuildType
- **Platform:** Windows (Local Build)
- **Build Tool:** PowerShell (cmake + ninja)

## About This Release

This is a local build of KatyPS5 $VersionTag created using:
- CMake (build configuration)
- Ninja (build tool)
- Qt6 (runtime libraries)
- Clang (C++ compiler)

### What's Included

- **katy_emulator.exe** - Main PlayStation 5 emulator
- **launcher.exe** - GUI launcher for easy game selection
- **Qt6 Runtime** - Complete Qt6 libraries required to run the emulator
- **Plugins** - Platform support, image formats, and GUI styling

### How to Use

1. Extract the release ZIP
2. Run `launcher.exe` to select and run PS5 games
3. Or use command line: `katy_emulator.exe --game "C:\path\to\game"`

See **GAME-LOADING.md** in the repository for game format information.

### System Requirements

- **OS:** Windows 10 or newer (64-bit)
- **RAM:** 8 GB minimum, 16 GB recommended
- **GPU:** NVIDIA or AMD with Vulkan support
- **Storage:** At least 50 GB free space for games

### Troubleshooting

If the emulator fails to start:
1. Ensure all files are in the same directory
2. Verify the directory structure is intact (all DLLs and plugins present)
3. Check that your GPU supports Vulkan
4. On first launch, you may need to download the latest GPU drivers

For more help, see:
- GitHub Issues: https://github.com/erickson558/KatyPS5/issues
- Documentation: https://github.com/erickson558/KatyPS5/blob/main/QUICKSTART.md

---

**Build Details:**
- Source: https://github.com/erickson558/KatyPS5
- License: GPL-2.0-only
- Upstream: https://github.com/KytyPS5/KytyPS5
"@

$notesContent | Out-File -FilePath $notesPath -Encoding UTF8 -Force
Write-Host "  ✓ Created notes.md" -ForegroundColor Green

Write-Host ""

# ============================================================================
# STEP 8: CREATE ZIP PACKAGE (OPTIONAL)
# ============================================================================

Write-Host "📦 Creating Windows package ZIP..." -ForegroundColor Yellow

$packagesDir = Join-Path $ReleaseDir "packages"
$windowsZipName = "KatyPS5-$VersionTag-Windows-x64.zip"
$windowsZipPath = Join-Path $packagesDir $windowsZipName

# Create ZIP of Windows release
if (Test-Path $windowsZipPath) {
    Remove-Item -Path $windowsZipPath -Force
}

# Use PowerShell's Compress-Archive (available in 5.1+)
try {
    Add-Type -AssemblyName System.IO.Compression.FileSystem -ErrorAction Stop
    $compressionLevel = [System.IO.Compression.CompressionLevel]::Optimal
    
    # Verify the Windows release directory exists and has content
    if (-not (Test-Path $WindowsReleaseDir)) {
        Write-Host "  ✗ ERROR: Windows release directory not found: $WindowsReleaseDir" -ForegroundColor Red
        Write-Host "  This usually means the compilation or packaging steps failed." -ForegroundColor Red
        exit 1
    }
    
    $itemsInDir = Get-ChildItem -Path $WindowsReleaseDir | Measure-Object
    if ($itemsInDir.Count -eq 0) {
        Write-Host "  ✗ ERROR: Windows release directory is empty: $WindowsReleaseDir" -ForegroundColor Red
        exit 1
    }
    
    [System.IO.Compression.ZipFile]::CreateFromDirectory(
        $WindowsReleaseDir,
        $windowsZipPath,
        $compressionLevel,
        $false
    )
    
    if (Test-Path $windowsZipPath) {
        $zipSize = (Get-Item $windowsZipPath).Length
        Write-Host "  ✓ Created ZIP package ($(($zipSize / 1MB).ToString('F2')) MB)" -ForegroundColor Green
        Write-Host "    File: $windowsZipName" -ForegroundColor Gray
    } else {
        Write-Host "  ✗ ZIP file was not created" -ForegroundColor Red
        exit 1
    }
} catch {
    Write-Host "  ✗ Could not create ZIP: $($_.Exception.Message)" -ForegroundColor Red
    Write-Host "  The release folder exists at: $ReleaseDir" -ForegroundColor Yellow
    Write-Host "  You can manually create the ZIP or try again." -ForegroundColor Yellow
    # Don't exit - allow user to continue with manual ZIP creation
}

Write-Host ""

# ============================================================================
# STEP 9: DISPLAY SUMMARY
# ============================================================================

Write-Host "═══════════════════════════════════════════════════════════════════" -ForegroundColor Green
Write-Host "  ✓ RELEASE PACKAGE CREATED SUCCESSFULLY" -ForegroundColor Green
Write-Host "═══════════════════════════════════════════════════════════════════" -ForegroundColor Green
Write-Host ""

Write-Host "📂 Release Location:" -ForegroundColor Cyan
Write-Host "   $ReleaseDir" -ForegroundColor White
Write-Host ""

Write-Host "📁 Release Contents:" -ForegroundColor Cyan
Write-Host "   ├─ windows/" -ForegroundColor White
Write-Host "   │  ├─ katy_emulator.exe ($(((Get-Item $emulatorExe).Length / 1MB).ToString('F2')) MB)" -ForegroundColor Gray
Write-Host "   │  ├─ launcher.exe" -ForegroundColor Gray
Write-Host "   │  ├─ Qt6*.dll (runtime libraries)" -ForegroundColor Gray
Write-Host "   │  ├─ plugins/ (platform support)" -ForegroundColor Gray
Write-Host "   │  └─ LICENSES/" -ForegroundColor Gray
Write-Host "   ├─ packages/" -ForegroundColor White
Write-Host "   │  └─ $windowsZipName ($(($zipSize / 1MB).ToString('F2')) MB)" -ForegroundColor Gray
Write-Host "   ├─ manifest.json" -ForegroundColor White
Write-Host "   └─ notes.md" -ForegroundColor White
Write-Host ""

Write-Host "🚀 Next Steps:" -ForegroundColor Cyan
Write-Host "   1. Test the emulator:" -ForegroundColor White
Write-Host "      cd `"$WindowsReleaseDir`"" -ForegroundColor Gray
Write-Host "      .\launcher.exe" -ForegroundColor Gray
Write-Host ""
Write-Host "   2. Run with a game:" -ForegroundColor White
Write-Host "      .\katy_emulator.exe --game `"C:\path\to\game`"" -ForegroundColor Gray
Write-Host ""
Write-Host "   3. Distribute the ZIP:" -ForegroundColor White
Write-Host "      $windowsZipPath" -ForegroundColor Gray
Write-Host ""

Write-Host "📊 Release Metadata:" -ForegroundColor Cyan
Write-Host "   Version: $Version" -ForegroundColor White
Write-Host "   Tag: $VersionTag" -ForegroundColor White
Write-Host "   Release Date: $releaseDate" -ForegroundColor White
Write-Host "   Commit: $commitShort ($gitBranch)" -ForegroundColor White
Write-Host "   Build Type: $BuildType" -ForegroundColor White
Write-Host ""

Write-Host "💾 To upload to GitHub, use:" -ForegroundColor Cyan
Write-Host "   gh release create $VersionTag --generate-notes" -ForegroundColor Gray
Write-Host "   gh release upload $VersionTag `"$windowsZipPath`"" -ForegroundColor Gray
Write-Host ""
